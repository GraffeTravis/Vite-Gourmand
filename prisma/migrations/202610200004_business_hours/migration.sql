BEGIN;
ALTER TABLE "BUSINESS_HOURS" ADD CONSTRAINT "BUSINESS_HOURS_times_valid" CHECK (
  ("IS_CLOSED" AND "OPENS_AT" IS NULL AND "CLOSES_AT" IS NULL)
  OR (NOT "IS_CLOSED" AND "OPENS_AT" IS NOT NULL AND "CLOSES_AT" IS NOT NULL AND "OPENS_AT" < "CLOSES_AT")
);

CREATE FUNCTION vg_assert_business_day(day_key integer) RETURNS void LANGUAGE plpgsql AS $$
BEGIN
  PERFORM pg_advisory_xact_lock(70400 + day_key);
  IF (EXISTS (SELECT 1 FROM "BUSINESS_HOURS" WHERE "WEEKDAY" = day_key AND "IS_CLOSED")
      AND (SELECT count(*) FROM "BUSINESS_HOURS" WHERE "WEEKDAY" = day_key) > 1)
     OR EXISTS (SELECT 1 FROM "BUSINESS_HOURS" a JOIN "BUSINESS_HOURS" b ON a."WEEKDAY" = b."WEEKDAY" AND a."ID" < b."ID"
                WHERE a."WEEKDAY" = day_key AND a."OPENS_AT" < b."CLOSES_AT" AND b."OPENS_AT" < a."CLOSES_AT") THEN
    RAISE EXCEPTION 'BUSINESS_HOURS_CONFLICT' USING ERRCODE = '23514';
  END IF;
END;
$$;
CREATE FUNCTION vg_validate_business_hours() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  IF TG_OP <> 'DELETE' THEN PERFORM vg_assert_business_day(NEW."WEEKDAY"); END IF;
  IF TG_OP <> 'INSERT' THEN PERFORM vg_assert_business_day(OLD."WEEKDAY"); END IF;
  RETURN NULL;
END;
$$;
CREATE CONSTRAINT TRIGGER "BUSINESS_HOURS_consistency" AFTER INSERT OR UPDATE OR DELETE ON "BUSINESS_HOURS"
  DEFERRABLE INITIALLY DEFERRED FOR EACH ROW EXECUTE FUNCTION vg_validate_business_hours();
COMMIT;
