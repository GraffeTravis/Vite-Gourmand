-- Contraintes complémentaires non exprimables dans le schéma Prisma 7.
-- Le modèle métier reste en revue : appliquer uniquement sur bases de test pour ce lot.
BEGIN;

ALTER TABLE "APP_USER" ADD CONSTRAINT "APP_USER_email_normalized"
  CHECK ("EMAIL" = lower(btrim("EMAIL")) AND length("EMAIL") > 3);

ALTER TABLE "MENU" ADD CONSTRAINT "MENU_values_valid"
  CHECK ("PRICE" >= 0 AND "MINIMUM_NUMBER_PEOPLE" >= 1 AND "STOCK" >= 0);
ALTER TABLE "MENU_IMAGE" ADD CONSTRAINT "MENU_IMAGE_order_valid" CHECK ("DISPLAY_ORDER" >= 0);
ALTER TABLE "MENU_FOOD" ADD CONSTRAINT "MENU_FOOD_order_valid" CHECK ("DISPLAY_ORDER" >= 0);

ALTER TABLE "CUSTOMER_ORDER" ADD CONSTRAINT "CUSTOMER_ORDER_quantity_valid"
  CHECK ("MINIMUM_PEOPLE_SNAPSHOT" >= 1 AND "NUMBER_PEOPLE" >= "MINIMUM_PEOPLE_SNAPSHOT");
ALTER TABLE "CUSTOMER_ORDER" ADD CONSTRAINT "CUSTOMER_ORDER_money_valid"
  CHECK (
    "UNIT_PRICE_APPLIED" >= 0 AND "MENU_SUBTOTAL" >= 0 AND "DISCOUNT_AMOUNT" >= 0
    AND "SHIPPING_COST" >= 0 AND "TOTAL_AMOUNT" >= 0
    AND ("SHIPPING_DISTANCE_KM" IS NULL OR "SHIPPING_DISTANCE_KM" >= 0)
    AND "MENU_SUBTOTAL" = "UNIT_PRICE_APPLIED" * "NUMBER_PEOPLE"
    AND "DISCOUNT_RATE" = CASE WHEN "NUMBER_PEOPLE" - "MINIMUM_PEOPLE_SNAPSHOT" >= 5 THEN 10 ELSE 0 END
    AND "DISCOUNT_AMOUNT" = round("MENU_SUBTOTAL" * "DISCOUNT_RATE" / 100, 2)
    AND "TOTAL_AMOUNT" = "MENU_SUBTOTAL" - "DISCOUNT_AMOUNT" + "SHIPPING_COST"
  );

ALTER TABLE "ORDER_HISTORY" ADD CONSTRAINT "ORDER_HISTORY_origin_actor_valid"
  CHECK (("ORIGIN" = 'USER' AND "ACTOR_ID" IS NOT NULL) OR ("ORIGIN" = 'SYSTEM' AND "ACTOR_ID" IS NULL));
ALTER TABLE "REVIEW" ADD CONSTRAINT "REVIEW_rating_valid" CHECK ("RATING" BETWEEN 1 AND 5);
ALTER TABLE "REVIEW" ADD CONSTRAINT "REVIEW_moderation_valid"
  CHECK (
    ("MODERATION_STATE" = 'PENDING' AND "MODERATOR_ID" IS NULL AND "MODERATED_AT" IS NULL)
    OR ("MODERATION_STATE" IN ('APPROVED', 'REJECTED') AND "MODERATOR_ID" IS NOT NULL AND "MODERATED_AT" IS NOT NULL)
  );
ALTER TABLE "BUSINESS_HOURS" ADD CONSTRAINT "BUSINESS_HOURS_weekday_valid" CHECK ("WEEKDAY" BETWEEN 1 AND 7);
ALTER TABLE "EQUIPMENT_RETURN" ADD CONSTRAINT "EQUIPMENT_RETURN_fee_valid" CHECK ("LATE_FEE_AMOUNT" >= 0);

ALTER TABLE "AUTH_SESSION" ADD CONSTRAINT "AUTH_SESSION_values_valid"
  CHECK ("TOKEN_HASH" ~ '^[0-9a-f]{64}$' AND "EXPIRES_AT" > "CREATED_AT" AND ("REVOKED_AT" IS NULL OR "REVOKED_AT" >= "CREATED_AT"));
ALTER TABLE "PASSWORD_RESET_TOKEN" ADD CONSTRAINT "PASSWORD_RESET_TOKEN_values_valid"
  CHECK ("TOKEN_HASH" ~ '^[0-9a-f]{64}$' AND "EXPIRES_AT" > "CREATED_AT" AND ("CONSUMED_AT" IS NULL OR "CONSUMED_AT" >= "CREATED_AT"));

ALTER TABLE "OUTBOX_EVENT" ADD CONSTRAINT "OUTBOX_EVENT_versions_valid"
  CHECK ("SCHEMA_VERSION" >= 1 AND "AGGREGATE_VERSION" >= 1 AND length(btrim("EVENT_KEY")) > 0);
ALTER TABLE "OUTBOX_DELIVERY" ADD CONSTRAINT "OUTBOX_DELIVERY_state_valid"
  CHECK ("STATE" IN ('PENDING', 'PROCESSING', 'SUCCEEDED', 'FAILED') AND "ATTEMPTS" >= 0);
ALTER TABLE "OUTBOX_DELIVERY" ADD CONSTRAINT "OUTBOX_DELIVERY_lease_valid"
  CHECK (
    ("STATE" = 'PROCESSING' AND "LEASE_TOKEN" IS NOT NULL AND "LOCKED_UNTIL" IS NOT NULL)
    OR ("STATE" <> 'PROCESSING' AND "LEASE_TOKEN" IS NULL AND "LOCKED_UNTIL" IS NULL)
  );
ALTER TABLE "OUTBOX_DELIVERY" ADD CONSTRAINT "OUTBOX_DELIVERY_processed_valid"
  CHECK (("STATE" = 'SUCCEEDED') = ("PROCESSED_AT" IS NOT NULL));

COMMIT;
